def generate_login(group, slug):
    """
    Собирает логин из слага группы и порядкового номера студента.

    group.slug уже валидирован (только строчные латинские буквы и цифры),
    slug студента — цифры. Результат нормализуется в нижний регистр.
    """
    return f'{group.slug}{slug}'.lower()

